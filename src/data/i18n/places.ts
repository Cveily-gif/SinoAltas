export type ProvinceLockup = {
  zh: string;
  en: string;
  gloss: string;
  hyphen: string;
  full: string;
};

export function provinceLockup(
  id: string,
  zhName: string,
  locale: "zh" | "en" = "zh",
): ProvinceLockup {
  const zh = zhName;
  const en = provinceEn[id] ?? zhName;
  const gloss = provinceGloss[id] ?? "";
  const hyphen = locale === "en" ? `${en}-${zh}` : `${zh}-${en}`;
  return {
    zh,
    en,
    gloss,
    hyphen,
    full: gloss ? `${hyphen} / ${gloss}` : hyphen,
  };
}

